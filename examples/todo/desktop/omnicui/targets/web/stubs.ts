// The web target's stub generator. omnicui runs it with every contract as JSON on standard input;
// it writes one TypeScript file per contract into the folder given as its argument (the app's
// src/omnicui/), which the components import.
// A contract change that a component no longer fits becomes a type error (npm run typecheck).
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

type Field = { name: string; type: string; enum?: unknown[]; default?: unknown; hasDefault: boolean };
type Contract = { id: string; file: string; props: Field[] | null; events: { name: string; fields: Field[] }[] | null; parts: { name: string; id: string }[] };

const contracts: Contract[] = JSON.parse(readFileSync(0, "utf8"));
const cap = (s: string) => s[0].toUpperCase() + s.slice(1);
const pascal = (id: string) => id.split(".").slice(1).map(cap).join("");
const short = (id: string) => id.split(".").pop()!;
const tsType = (f: Field) =>
  f.enum ? f.enum.map((v) => JSON.stringify(v)).join(" | ") : ({ string: "string", integer: "number", number: "number", boolean: "boolean" } as Record<string, string>)[f.type];

const out = process.argv[2];
if (!out) throw new Error("usage: node stubs.ts <output folder>");
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const index: string[] = [];
for (const c of contracts) {
  const name = pascal(c.id);
  const lines = [`// Generated from ${c.file} by stubs.ts. Do not edit: change the contract instead.`, ""];
  for (const e of c.events ?? []) {
    lines.push(`export interface ${name}${cap(e.name)} { ${e.fields.map((f) => `${f.name}: ${tsType(f)};`).join(" ")} }`);
  }
  const props = (c.props ?? []).map((p) => `  ${p.name}?: ${tsType(p)};`);
  const handlers = (c.events ?? []).map((e) => `  on${cap(e.name)}?: (event: ${name}${cap(e.name)}) => void;`);
  lines.push(`export interface ${name}Props {`, ...props, ...handlers, `}`);
  const defaults = (c.props ?? []).filter((p) => p.hasDefault).map((p) => `${p.name}: ${JSON.stringify(p.default)}`);
  lines.push(`export const ${name}Defaults = { ${defaults.join(", ")} } as const;`);
  lines.push(`export const Parts = { ${c.parts.map((p) => `${p.name}: ${JSON.stringify(p.id)}`).join(", ")} } as const;`);
  lines.push(`export const Events = [${(c.events ?? []).map((e) => JSON.stringify(e.name)).join(", ")}] as const;`, "");
  writeFileSync(`${out}/${short(c.id)}.ts`, lines.join("\n"));
  index.push(`  ${JSON.stringify(c.id)}: [${(c.events ?? []).map((e) => JSON.stringify(e.name)).join(", ")}],`);
}
writeFileSync(
  `${out}/index.ts`,
  `// Generated by stubs.ts. The events each component reports, for the harness to listen to.\nexport const EVENTS: Record<string, readonly string[]> = {\n${index.join("\n")}\n};\n`,
);
