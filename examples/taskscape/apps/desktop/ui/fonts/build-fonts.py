"""Builds the desktop app's fonts from the web widget library's (packages/ui/src/styles/fonts):

- Inter at the weights the app uses, as static TTFs (egui cannot pick a weight in a variable font);
- the Material Symbols subset as a TTF, and icons.rs: each icon name with its codepoint, since egui
  draws text, not ligatures.

    TASKSCAPE_REFERENCE_SRC=<reference>/main/src:<reference>/tray/src python3 apps/desktop/ui/fonts/build-fonts.py   (fontTools, brotli)
"""
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

HERE = Path(__file__).parent
WEB = HERE.parents[3] / "packages" / "ui" / "src" / "styles" / "fonts"
WEIGHTS = {"Regular": 400, "Medium": 500, "SemiBold": 600, "Bold": 700}

for name, weight in WEIGHTS.items():
    font = TTFont(WEB / "inter-latin.woff2")
    static = instancer.instantiateVariableFont(font, {"wght": weight, "opsz": 14} if "opsz" in [a.axisTag for a in font["fvar"].axes] else {"wght": weight})
    static.flavor = None
    static.save(HERE / f"Inter-{name}.ttf")

# The icons: Material Symbols cut down to every icon the web code and the desktop code name, plus the
# reference app's (TASKSCAPE_REFERENCE_SRC: its main/src and tray/src, for the desktop-only screens),
# with the ligature names mapped to their codepoints (egui draws text, not ligatures).
import os
import re
from fontTools import subset

REPO = HERE.parents[3]
FULL = REPO / "node_modules" / "material-symbols" / "material-symbols-outlined.woff2"
known = set(TTFont(FULL).getGlyphOrder())
LITERAL = re.compile(r"""["'`]([a-z0-9_]{2,60})["'`]""")
names = set()
for top in [REPO / "packages/ui/src", REPO / "apps"] + [Path(p) for p in os.environ.get("TASKSCAPE_REFERENCE_SRC", "").split(":") if p]:
    for f in top.rglob("*"):
        if f.suffix in (".ts", ".tsx", ".rs") and "node_modules" not in f.parts and "target" not in f.parts:
            names |= {m for m in LITERAL.findall(f.read_text(encoding="utf-8", errors="ignore")) if m in known}
font = TTFont(FULL)
opts = subset.Options(); opts.layout_features = ["rlig", "rclt", "liga"]; opts.layout_closure = False; opts.notdef_outline = True; opts.glyph_names = True
s = subset.Subsetter(opts)
web = set(TTFont(WEB / "material-symbols-subset.woff2").getGlyphOrder()) & known
s.populate(glyphs=sorted(names | web), text="abcdefghijklmnopqrstuvwxyz0123456789_")
s.subset(font)
cmap = font.getBestCmap()
by_glyph = {g: cp for cp, g in cmap.items() if cp >= 0xE000}
letter = {g: chr(cp) for cp, g in cmap.items() if cp < 0xE000}
lig = {}
for lookup in font["GSUB"].table.LookupList.Lookup:
    for st in lookup.SubTable:
        st = getattr(st, "ExtSubTable", st)
        for first, ligs in getattr(st, "ligatures", {}).items():
            for l in ligs:
                glyphs = [first] + list(l.Component)
                if all(g in letter for g in glyphs) and l.LigGlyph in by_glyph:
                    lig["".join(letter[g] for g in glyphs)] = by_glyph[l.LigGlyph]
font = instancer.instantiateVariableFont(font, {a.axisTag: (a.defaultValue if a.axisTag != "wght" else 350) for a in font["fvar"].axes})
font.flavor = None
font.save(str(HERE / "MaterialSymbols.ttf"))
have = sorted(lig)
print(len(have), "icon names;", "screenshot_monitor" in lig, "crop_free" in lig, "restore" in lig, "check" in lig)
lines = ["//! Generated by fonts/build-fonts.py from Material Symbols: every icon the web, the desktop and the reference app name. Do not edit.", "", "/// Icon name → codepoint in MaterialSymbols.ttf.", "pub const ICONS: &[(&str, char)] = &["]
lines += [f'    ("{n}", \'\\u{{{lig[n]:04x}}}\'),' for n in have]
lines += ["];", ""]
(HERE.parent / "src" / "icons.rs").write_text("\n".join(lines))
