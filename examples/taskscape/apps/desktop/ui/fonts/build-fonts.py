"""Builds the desktop app's fonts from the web widget library's (packages/ui/src/styles/fonts):

- Inter at the weights the app uses, as static TTFs (egui cannot pick a weight in a variable font);
- the Material Symbols subset as a TTF, and icons.rs: each icon name with its codepoint, since egui
  draws text, not ligatures.

    python3 apps/desktop/ui/fonts/build-fonts.py      (needs fontTools and brotli)
"""
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

HERE = Path(__file__).parent
WEB = HERE.parents[3] / "packages" / "ui" / "src" / "styles" / "fonts"
WEIGHTS = {"Regular": 400, "Medium": 500, "SemiBold": 600, "Bold": 700}

for name, weight in WEIGHTS.items():
    font = TTFont(WEB / "inter-latin.woff2")
    static = instancer.instantiateVariableFont(font, {"wght": weight, "opsz": 14} if "opsz" in [a.axisTag for a in font["fvar"].axes] else {"wght": weight})
    static.flavor = None
    static.save(HERE / f"Inter-{name}.ttf")

icons = TTFont(WEB / "material-symbols-subset.woff2")
if "fvar" in icons:
    icons = instancer.instantiateVariableFont(icons, {a.axisTag: (a.defaultValue if a.axisTag != "wght" else 350) for a in icons["fvar"].axes})
icons.flavor = None
icons.save(HERE / "MaterialSymbols.ttf")

# The ligature table maps a name ("check") to a glyph; the cmap maps a private-use codepoint to it.
by_glyph = {g: cp for cp, g in icons.getBestCmap().items() if cp >= 0xE000}
lig = {}
for lookup in icons["GSUB"].table.LookupList.Lookup:
    for st in lookup.SubTable:
        st = getattr(st, "ExtSubTable", st)
        for first, ligs in getattr(st, "ligatures", {}).items():
            for l in ligs:
                glyphs = [first] + list(l.Component)
                text = "".join(chr(cp) for g in glyphs for cp, gg in icons.getBestCmap().items() if gg == g and cp < 0xE000)
                if l.LigGlyph in by_glyph and len(text) == len(glyphs):
                    lig[text] = by_glyph[l.LigGlyph]
lines = ["//! Generated by fonts/build-fonts.py from the Material Symbols subset. Do not edit.", "", "/// Icon name → codepoint in MaterialSymbols.ttf.", "pub const ICONS: &[(&str, char)] = &["]
lines += [f'    ("{n}", \'\\u{{{cp:04x}}}\'),' for n, cp in sorted(lig.items())]
lines += ["];", ""]
(HERE.parent / "src" / "icons.rs").parent.mkdir(exist_ok=True)
(HERE.parent / "src" / "icons.rs").write_text("\n".join(lines))
print(len(lig), "icons;", ", ".join(f"Inter-{n}" for n in WEIGHTS))
