"""Writes src/tokens.rs: the web widget library's colour tokens (packages/ui/src/styles/tokens.css),
light and dark, converted from OKLCH to sRGB for egui.

    python3 apps/desktop/ui/fonts/build-tokens.py
"""
import math
import re
from pathlib import Path

HERE = Path(__file__).parent
CSS = (HERE.parents[3] / "packages" / "ui" / "src" / "styles" / "tokens.css").read_text()


def block(selector):
    m = re.search(re.escape(selector) + r"\s*\{(.*?)\n\}", CSS, re.S)
    return dict(re.findall(r"--([a-z0-9-]+):\s*oklch\(([^)]*)\)", m.group(1)))


def srgb(oklch):
    parts = oklch.replace("/", " ").split()
    L, C, H = float(parts[0]), float(parts[1]), float(parts[2])
    alpha = float(parts[3]) if len(parts) > 3 else 1.0
    a, b = C * math.cos(math.radians(H)), C * math.sin(math.radians(H))
    l_ = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m_ = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s_ = (L - 0.0894841775 * a - 1.2914855480 * b) ** 3
    lin = (4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
           -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
           -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_)
    def gamma(x):
        x = min(max(x, 0.0), 1.0)
        return 12.92 * x if x <= 0.0031308 else 1.055 * x ** (1 / 2.4) - 0.055
    r, g, b2 = (round(gamma(c) * 255) for c in lin)
    return r, g, b2, round(alpha * 255)


light, dark = block(":root"), block(".dark")
names = list(light)
out = ["//! Generated by fonts/build-tokens.py from the web widget library's tokens.css. Do not edit.",
       "use egui::Color32;", "",
       "/// One colour per role, as the web's CSS variables name them (--surface-1 is surface_1).",
       "#[derive(Clone, Copy, Debug)]", "pub struct Tokens {"]
out += [f"    pub {n.replace('-', '_')}: Color32," for n in names]
out += ["}", ""]
for label, values in (("LIGHT", light), ("DARK", {**light, **dark})):
    out.append(f"pub const {label}: Tokens = Tokens {{")
    for n in names:
        r, g, b, a = srgb(values[n])
        ctor = f"Color32::from_rgb({r}, {g}, {b})" if a == 255 else f"Color32::from_rgba_unmultiplied_const({r}, {g}, {b}, {a})"
        out.append(f"    {n.replace('-', '_')}: {ctor},")
    out.append("};")
    out.append("")
(HERE.parent / "src" / "tokens.rs").write_text("\n".join(out))
print(len(names), "tokens")
