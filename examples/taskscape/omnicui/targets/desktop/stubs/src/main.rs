//! The egui target's stub generator. omnicui runs it with every contract as JSON on standard
//! input; it writes one Rust module per contract into the folder given as its argument (the app's
//! src/omnicui/). The components import them,
//! so a contract change they no longer fit becomes a compile error.
use serde::Deserialize;
use std::fmt::Write;

#[derive(Deserialize)]
struct Field {
    name: String,
    #[serde(rename = "type")]
    ty: String,
    #[serde(default)]
    default: serde_json::Value,
    #[serde(rename = "hasDefault")]
    has_default: bool,
}

#[derive(Deserialize)]
struct Event {
    name: String,
    fields: Vec<Field>,
}

#[derive(Deserialize)]
struct Part {
    name: String,
    id: String,
}

#[derive(Deserialize)]
struct Contract {
    id: String,
    file: String,
    props: Option<Vec<Field>>,
    events: Option<Vec<Event>>,
    parts: Vec<Part>,
}

fn rust_type(f: &Field) -> &'static str {
    match f.ty.as_str() {
        "string" => "String",
        "integer" => "i64",
        "number" => "f64",
        _ => "bool",
    }
}

/// A field name as a Rust identifier: a keyword (type, as, ref…) is written raw (r#type).
fn ident(s: &str) -> String {
    const KEYWORDS: &[&str] = &["as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where", "while", "box", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen"];
    if KEYWORDS.contains(&s) { format!("r#{s}") } else { s.to_owned() }
}

fn pascal(s: &str) -> String {
    let mut c = s.chars();
    c.next().map(|f| f.to_uppercase().chain(c).collect()).unwrap_or_default()
}

fn literal(f: &Field) -> String {
    match (&f.default, f.ty.as_str()) {
        (serde_json::Value::String(s), _) => format!("{s:?}.to_owned()"),
        (serde_json::Value::Null, "string") => "String::new()".into(),
        (serde_json::Value::Null, "boolean") => "false".into(),
        (serde_json::Value::Null, "number") => "0.0".into(),
        (serde_json::Value::Null, _) => "0".into(),
        (v, "number") if v.is_i64() => format!("{v}.0"),
        (v, _) => v.to_string(),
    }
}

fn main() {
    let contracts: Vec<Contract> = serde_json::from_reader(std::io::stdin()).expect("contracts as JSON on stdin");
    let out = std::env::args().nth(1).expect("usage: omnicui-egui-stubs <output folder>");
    let dir = std::path::Path::new(&out);
    // omnicui runs this before each check, while other checks may be building against the folder:
    // never empty it, and write a file only when its content changes (to a temporary name, then renamed).
    std::fs::create_dir_all(dir).unwrap_or_else(|e| panic!("create {out}: {e}"));
    let mut modules = String::from("//! Generated by the stub generator from contracts/. Do not edit.\n");
    for c in &contracts {
        let short = c.id.rsplit('.').next().unwrap();
        let name = pascal(short);
        let mut s = String::new();
        writeln!(s, "//! Generated from {} by the stub generator. Do not edit: change the contract instead.\n", c.file).unwrap();
        writeln!(s, "/// The props of `{}`, with the contract's defaults.", c.id).unwrap();
        writeln!(s, "#[derive(Debug, Clone, serde::Deserialize)]\n#[serde(default)]\npub struct {name}Props {{").unwrap();
        for p in c.props.iter().flatten() {
            writeln!(s, "    pub {}: {},", ident(&p.name), rust_type(p)).unwrap();
        }
        writeln!(s, "}}\n\nimpl Default for {name}Props {{\n    fn default() -> Self {{\n        Self {{").unwrap();
        for p in c.props.iter().flatten() {
            let _ = p.has_default;
            writeln!(s, "            {}: {},", ident(&p.name), literal(p)).unwrap();
        }
        writeln!(s, "        }}\n    }}\n}}\n").unwrap();
        writeln!(s, "/// The events `{}` reports.\n#[derive(Debug, Clone)]\npub enum {name}Event {{", c.id).unwrap();
        for e in c.events.iter().flatten() {
            let fields: Vec<String> = e.fields.iter().map(|f| format!("{}: {}", ident(&f.name), rust_type(f))).collect();
            writeln!(s, "    {} {{ {} }},", pascal(&e.name), fields.join(", ")).unwrap();
        }
        // An enum with no variants is matched through the value, not the reference.
        let scrutinee = if c.events.iter().flatten().next().is_some() { "self" } else { "*self" };
        writeln!(s, "}}\n\nimpl {name}Event {{\n    /// The event's contract name and fields, as omnicui receives them.\n    pub fn to_json(&self) -> (&'static str, serde_json::Value) {{\n        match {scrutinee} {{").unwrap();
        for e in c.events.iter().flatten() {
            let names: Vec<String> = e.fields.iter().map(|f| ident(&f.name)).collect();
            let obj: Vec<String> = e.fields.iter().zip(&names).map(|(f, n)| format!("{:?}: {n}", f.name)).collect();
            writeln!(s, "            Self::{} {{ {} }} => ({:?}, serde_json::json!({{ {} }})),", pascal(&e.name), names.join(", "), e.name, obj.join(", ")).unwrap();
        }
        writeln!(s, "        }}\n    }}\n}}\n\n/// The part ids, as every target names them.\npub mod parts {{").unwrap();
        for p in &c.parts {
            writeln!(s, "    pub const {}: &str = {:?};", p.name.to_uppercase(), p.id).unwrap();
        }
        writeln!(s, "}}").unwrap();
        write_if_changed(&dir.join(format!("{short}.rs")), &s);
        writeln!(modules, "pub mod {short};").unwrap();
    }
    write_if_changed(&dir.join("mod.rs"), &modules);
}

fn write_if_changed(path: &std::path::Path, text: &str) {
    if std::fs::read_to_string(path).ok().as_deref() == Some(text) {
        return;
    }
    let tmp = path.with_extension("rs.tmp");
    std::fs::write(&tmp, text).expect("write a stub");
    std::fs::rename(&tmp, path).expect("rename a stub");
}
