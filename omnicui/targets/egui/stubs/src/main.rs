//! The egui target's stub generator. omnicui runs it with every contract as JSON on standard
//! input; it writes one Rust module per contract into the folder given as its argument (the app's
//! src/omnicui/). The components import them,
//! so a contract change they no longer fit becomes a compile error.
use serde::Deserialize;
use std::fmt::Write;

#[derive(Deserialize)]
struct Field {
    name: String,
    #[serde(rename = "type")]
    ty: String,
    #[serde(default)]
    default: serde_json::Value,
    #[serde(rename = "hasDefault")]
    has_default: bool,
}

#[derive(Deserialize)]
struct Event {
    name: String,
    fields: Vec<Field>,
}

#[derive(Deserialize)]
struct Part {
    name: String,
    id: String,
}

#[derive(Deserialize)]
struct Contract {
    id: String,
    file: String,
    props: Option<Vec<Field>>,
    events: Option<Vec<Event>>,
    parts: Vec<Part>,
}

fn rust_type(f: &Field) -> &'static str {
    match f.ty.as_str() {
        "string" => "String",
        "integer" => "i64",
        "number" => "f64",
        _ => "bool",
    }
}

fn pascal(s: &str) -> String {
    let mut c = s.chars();
    c.next().map(|f| f.to_uppercase().chain(c).collect()).unwrap_or_default()
}

fn literal(f: &Field) -> String {
    match (&f.default, f.ty.as_str()) {
        (serde_json::Value::String(s), _) => format!("{s:?}.to_owned()"),
        (serde_json::Value::Null, "string") => "String::new()".into(),
        (serde_json::Value::Null, "boolean") => "false".into(),
        (serde_json::Value::Null, "number") => "0.0".into(),
        (serde_json::Value::Null, _) => "0".into(),
        (v, "number") if v.is_i64() => format!("{v}.0"),
        (v, _) => v.to_string(),
    }
}

fn main() {
    let contracts: Vec<Contract> = serde_json::from_reader(std::io::stdin()).expect("contracts as JSON on stdin");
    let out = std::env::args().nth(1).expect("usage: omnicui-egui-stubs <output folder>");
    let dir = std::path::Path::new(&out);
    let _ = std::fs::remove_dir_all(dir);
    std::fs::create_dir_all(dir).unwrap_or_else(|e| panic!("create {out}: {e}"));
    let mut modules = String::from("//! Generated by the stub generator from contracts/. Do not edit.\n");
    for c in &contracts {
        let short = c.id.rsplit('.').next().unwrap();
        let name = pascal(short);
        let mut s = String::new();
        writeln!(s, "//! Generated from {} by the stub generator. Do not edit: change the contract instead.\n", c.file).unwrap();
        writeln!(s, "/// The props of `{}`, with the contract's defaults.", c.id).unwrap();
        writeln!(s, "#[derive(Debug, Clone, serde::Deserialize)]\n#[serde(default)]\npub struct {name}Props {{").unwrap();
        for p in c.props.iter().flatten() {
            writeln!(s, "    pub {}: {},", p.name, rust_type(p)).unwrap();
        }
        writeln!(s, "}}\n\nimpl Default for {name}Props {{\n    fn default() -> Self {{\n        Self {{").unwrap();
        for p in c.props.iter().flatten() {
            let _ = p.has_default;
            writeln!(s, "            {}: {},", p.name, literal(p)).unwrap();
        }
        writeln!(s, "        }}\n    }}\n}}\n").unwrap();
        writeln!(s, "/// The events `{}` reports.\n#[derive(Debug, Clone)]\npub enum {name}Event {{", c.id).unwrap();
        for e in c.events.iter().flatten() {
            let fields: Vec<String> = e.fields.iter().map(|f| format!("{}: {}", f.name, rust_type(f))).collect();
            writeln!(s, "    {} {{ {} }},", pascal(&e.name), fields.join(", ")).unwrap();
        }
        writeln!(s, "}}\n\nimpl {name}Event {{\n    /// The event's contract name and fields, as omnicui receives them.\n    pub fn to_json(&self) -> (&'static str, serde_json::Value) {{\n        match self {{").unwrap();
        for e in c.events.iter().flatten() {
            let names: Vec<&str> = e.fields.iter().map(|f| f.name.as_str()).collect();
            let obj: Vec<String> = names.iter().map(|n| format!("{n:?}: {n}")).collect();
            writeln!(s, "            Self::{} {{ {} }} => ({:?}, serde_json::json!({{ {} }})),", pascal(&e.name), names.join(", "), e.name, obj.join(", ")).unwrap();
        }
        writeln!(s, "        }}\n    }}\n}}\n\n/// The part ids, as every target names them.\npub mod parts {{").unwrap();
        for p in &c.parts {
            writeln!(s, "    pub const {}: &str = {:?};", p.name.to_uppercase(), p.id).unwrap();
        }
        writeln!(s, "}}").unwrap();
        std::fs::write(dir.join(format!("{short}.rs")), s).expect("write a stub");
        writeln!(modules, "pub mod {short};").unwrap();
    }
    std::fs::write(dir.join("mod.rs"), modules).expect("write mod.rs");
}
